#!/usr/bin/env node
// Regenerates frontend/wailsjs/go/{main/App.js, main/App.d.ts, models.ts}
// from the exported methods of *App in app.go and the structs in
// internal/models, in the same shape `wails generate module` produces.
//
// The Wails build writes its own copy to frontend/dist/wailsjs (git-ignored);
// app.js calls window.go.main.App.* directly, so these committed files are a
// readable, typed reference of the backend API. Run after changing an App
// method:  node scripts/gen-bindings.js

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'frontend', 'wailsjs', 'go');
const HEADER = '// Cynhyrchwyd y ffeil hon yn awtomatig. PEIDIWCH Â MODIWL\n// This file is automatically generated. DO NOT EDIT\n';

// Methods on *App that are not bound (lifecycle hooks, lower-case helpers
// are skipped automatically).
const SKIP = new Set([]);

function goTypeToTS(t, structs) {
    t = t.trim();
    if (t.startsWith('*')) return goTypeToTS(t.slice(1), structs);
    if (t.startsWith('[]')) {
        const inner = t.slice(2);
        if (inner === 'byte') return 'Array<number>';
        return 'Array<' + goTypeToTS(inner, structs) + '>';
    }
    if (t.startsWith('map[')) {
        const close = t.indexOf(']');
        return '{[key: ' + goTypeToTS(t.slice(4, close), structs) + ']: ' + goTypeToTS(t.slice(close + 1), structs) + '}';
    }
    switch (t) {
        case 'string': return 'string';
        case 'bool': return 'boolean';
        case 'int': case 'int32': case 'int64': case 'float64': case 'uint': return 'number';
        case 'time.Time': return 'any';
        case 'error': return 'void';
        case 'interface{}': case 'any': return 'any';
    }
    const name = t.replace(/^models\./, '').replace(/^storage\./, '');
    if (structs[name]) return 'models.' + name;
    return 'any';
}

// Parse `type X struct { Field Type `json:"name,omitempty"` }` blocks.
function parseStructs(files) {
    const structs = {};
    for (const f of files) {
        const src = fs.readFileSync(f, 'utf8');
        const re = /type (\w+) struct \{([\s\S]*?)\n\}/g;
        let m;
        while ((m = re.exec(src))) {
            const fields = [];
            for (const line of m[2].split('\n')) {
                const fm = line.match(/^\s*(\w+)\s+([^\s`]+)\s+`json:"([^"]+)"`/);
                if (!fm) continue;
                const [name, ...opts] = fm[3].split(',');
                if (name === '-') continue;
                fields.push({ goName: fm[1], goType: fm[2], json: name, optional: opts.includes('omitempty') });
            }
            structs[m[1]] = fields;
        }
    }
    return structs;
}

// Split "a string, b int" (Go allows "a, b string") into typed params.
function parseParams(src) {
    src = src.trim();
    if (!src) return [];
    const parts = src.split(',').map((p) => p.trim());
    const out = [];
    let pendingNames = [];
    for (const p of parts) {
        const sp = p.split(/\s+/);
        if (sp.length === 1) { pendingNames.push(sp[0]); continue; }
        const type = sp.slice(1).join(' ');
        for (const n of pendingNames) out.push({ name: n, type });
        pendingNames = [];
        out.push({ name: sp[0], type });
    }
    return out;
}

function parseMethods(file) {
    const src = fs.readFileSync(file, 'utf8');
    const re = /^func \(a \*App\) ([A-Z]\w*)\(([^)]*)\)\s*(\([^)]*\)|[^{\s]+)?\s*\{/gm;
    const methods = [];
    let m;
    while ((m = re.exec(src))) {
        if (SKIP.has(m[1])) continue;
        let rets = (m[3] || '').replace(/^\(|\)$/g, '').split(',').map((s) => s.trim()).filter(Boolean);
        rets = rets.filter((r) => r !== 'error');
        methods.push({ name: m[1], params: parseParams(m[2]), ret: rets[0] || null });
    }
    return methods.sort((a, b) => a.name.localeCompare(b.name));
}

function main() {
    const modelFiles = fs.readdirSync(path.join(ROOT, 'internal', 'models'))
        .filter((f) => f.endsWith('.go') && !f.endsWith('_test.go'))
        .map((f) => path.join(ROOT, 'internal', 'models', f));
    const structs = parseStructs(modelFiles);
    const methods = parseMethods(path.join(ROOT, 'app.go'));

    // App.js
    let js = '// @ts-check\n' + HEADER + '\n';
    for (const m of methods) {
        const args = m.params.map((_, i) => 'arg' + (i + 1)).join(', ');
        js += 'export function ' + m.name + '(' + args + ') {\n' +
            "  return window['go']['main']['App']['" + m.name + "'](" + args + ');\n}\n\n';
    }

    // App.d.ts
    let dts = HEADER + "import {models} from '../models';\n\n";
    for (const m of methods) {
        const args = m.params.map((p, i) => 'arg' + (i + 1) + ':' + goTypeToTS(p.type, structs)).join(',');
        const ret = m.ret ? goTypeToTS(m.ret, structs) : 'void';
        dts += 'export function ' + m.name + '(' + args + '):Promise<' + ret + '>;\n\n';
    }

    // models.ts (interfaces are enough for a reference; Wails emits classes)
    let ts = 'export namespace models {\n';
    for (const name of Object.keys(structs).sort()) {
        ts += '\n\texport interface ' + name + ' {\n';
        for (const f of structs[name]) {
            ts += '\t    ' + f.json + (f.optional ? '?' : '') + ': ' + goTypeToTS(f.goType, structs) + ';\n';
        }
        ts += '\t}\n';
    }
    ts += '\n}\n';

    fs.mkdirSync(path.join(OUT, 'main'), { recursive: true });
    fs.writeFileSync(path.join(OUT, 'main', 'App.js'), js.trimEnd() + '\n');
    fs.writeFileSync(path.join(OUT, 'main', 'App.d.ts'), dts.trimEnd() + '\n');
    fs.writeFileSync(path.join(OUT, 'models.ts'), ts);
    console.log('Wrote ' + methods.length + ' App methods and ' + Object.keys(structs).length + ' model types.');
}

main();
